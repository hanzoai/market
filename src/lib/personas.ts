export function personaSummary(p: PersonaEntry): string {
  if (p.about) return p.about
  const role = p.category.replace(/_/g, ' ')
  return `${p.name} (${role}) — Open-source cognitive persona and psychometric profile from @hanzo/personas.`
}

export function personas({
  q = '',
  category = '',
  limit = 48,
  offset = 0,
}: {
  q?: string
  category?: string
  limit?: number
  offset?: number
}): { personas: PersonaEntry[]; total: number } {
  let res = PERSONAS
  if (q.trim()) {
    const words = q.trim().toLowerCase().split(/\s+/).filter(Boolean)
    res = res.filter((p) => {
      const hay = `${p.name} ${p.called ?? ''} ${p.category} ${p.about ?? ''} ${p.based ?? ''} ${p.slug}`.toLowerCase()
      return words.every((w) => hay.includes(w))
    })
  }
  if (category) {
    res = res.filter((p) => p.category.toLowerCase() === category.toLowerCase())
  }
  return {
    personas: res.slice(offset, offset + limit),
    total: res.length,
  }
}

export function findPersona(slug: string): PersonaEntry | undefined {
  return PERSONAS.find((p) => p.slug === slug)
}

